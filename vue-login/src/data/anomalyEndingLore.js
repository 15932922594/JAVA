/** 规范化：保证每个 lore 都有组件需要的全部字段，缺字段时用安全兜底 */
function normalize(entry) {
  return {
    stamp: entry?.stamp || '',
    status: entry?.status || '主体状态 · 未记录',
    epilogue: Array.isArray(entry?.epilogue) ? entry.epilogue : [],
    dossier: entry?.dossier || '归档信息缺失。',
    tags: Array.isArray(entry?.tags) ? entry.tags : [],
    omen: entry?.omen || '档案链中断。'
  }
}

/**
 * 取某个结局的余波档案。
 * @param {string} key 形如 'echo-ward:e_room0'，终局为 'finale'
 * @returns {{stamp:string,status:string,epilogue:string[],dossier:string,tags:string[],omen:string}}
 */
export function loreFor(key) {
  return normalize(LORE[key])
}
