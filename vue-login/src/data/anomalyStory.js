/** 全部结局按副本分组，便于图鉴统计 */
export function allEndings() {
  const map = {}
  CASES.forEach((c) => {
    map[c.id] = Object.entries(c.endings).map(([id, e]) => ({ id, ...e }))
  })
  return map
}
